val ALL_EMOJIS: List<String> = EMOJI_GROUPS.flatMap { it.emojis }.distinct()

fun searchEmojis(query: String, groupLabel: String? = null): List<String> {
    val clean = query.trim()
    return EMOJI_GROUPS
        .asSequence()
        .filter { groupLabel == null || it.label == groupLabel }
        .filter { group ->
            clean.isBlank() ||
                group.label.contains(clean, ignoreCase = true) ||
                group.keywords.any { it.contains(clean, ignoreCase = true) } ||
                group.emojis.any { it == clean }
        }
        .flatMap { it.emojis.asSequence() }
        .distinct()
        .toList()
}
